#!/usr/bin/env python3
"""Task 9 — storage & throughput benchmark (measured, not estimated).

Part A: per-observation timing (load / compute / write), input/output size, and
        peak RSS over a representative sample stratified by file size (incl. the
        largest events -> worst case).
Part B: parallel-scaling sweep (throughput vs. worker count) to find optimal
        parallelism.
Part C: projections (full-catalog runtime, Tier B storage, injection/null storage).

Writes bench_results.json. The two markdown reports are generated by
make_reports.py from this JSON.

Usage:
  benchmark.py --config CONFIG --source-root DIR --checksums RAW.parquet \
     --tier-b-manifest TB.parquet --sample 60 --workers-sweep 1,2,4,8,14,16 \
     --out bench_results.json
"""
import argparse
import json
import os
import resource
import tempfile
import time
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import pandas as pd

from echo_frb.preprocess import standardize as S


def stratified_sample(sizes_df, n):
    """Pick n files spanning the size range, guaranteeing the largest few."""
    d = sizes_df.sort_values("size_bytes").reset_index(drop=True)
    idx = np.linspace(0, len(d) - 1, n - 5).astype(int)
    picks = set(idx.tolist()) | set(range(len(d) - 5, len(d)))  # + 5 largest
    return list(d.iloc[sorted(picks)].abspath)


def bench_one(path, cfg, src_sha):
    t0 = time.perf_counter()
    (data, flag, gf, freqs, times, tu, pr, meta) = S.load_tier_a(path)
    t1 = time.perf_counter()
    prod = S.standardize(data, flag, gf, pr, cfg)
    t2 = time.perf_counter()
    prov = dict(source_file=os.path.basename(path), source_sha256=src_sha or "",
                config_hash=cfg["_config_hash"], code_commit="bench",
                preprocessing_version=cfg["preprocessing_version"],
                tns_name=meta["tns_name"], event_id=meta["event_id"],
                dm_incoherent=meta["dm_incoherent"], res_time=meta["res_time"],
                res_freq=meta["res_freq"], num_time=meta["num_time"])
    prov["content_sha256"] = S.content_sha256(prod, prov)
    with tempfile.TemporaryDirectory() as td:
        out = os.path.join(td, "o_tierb.h5")
        S.write_tier_b(out, prod, dict(freqs=freqs, times=times, times_unix=tu),
                       prov, cfg)
        t3 = time.perf_counter()
        out_size = os.path.getsize(out)
    return dict(file=os.path.basename(path), in_size=os.path.getsize(path),
                out_size=out_size, num_time=int(data.shape[1]),
                load_s=t1 - t0, compute_s=t2 - t1, write_s=t3 - t2,
                total_s=t3 - t0,
                maxrss_kb=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


def _bench_worker(args):
    return bench_one(*args)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--source-root", required=True)
    ap.add_argument("--checksums", required=True)
    ap.add_argument("--tier-b-manifest", required=True)
    ap.add_argument("--sample", type=int, default=60)
    ap.add_argument("--workers-sweep", default="1,2,4,8,14,16")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    cfg = S.load_config(args.config)
    raw = pd.read_parquet(args.checksums)
    h5 = raw[raw.relpath.str.startswith("dynamic_spectra/data/")
             & raw.relpath.str.endswith(".h5")].copy()
    sha_by = dict(zip(h5.abspath.map(os.path.basename), h5.sha256))
    sample = stratified_sample(h5[["abspath", "size_bytes"]], args.sample)
    print(f"[bench] sample of {len(sample)} files "
          f"({h5.size_bytes.min()/1e6:.1f}-{h5.size_bytes.max()/1e6:.1f} MB range)")

    # ---- Part A: per-observation, serial ----
    rows = [bench_one(p, cfg, sha_by.get(os.path.basename(p))) for p in sample]
    a = pd.DataFrame(rows)

    def stats(col):
        s = a[col]
        return dict(mean=float(s.mean()), median=float(s.median()),
                    p95=float(s.quantile(0.95)), max=float(s.max()))

    partA = dict(
        n=len(a),
        in_size_mb=stats("in_size").__class__ and {k: v / 1e6 for k, v in stats("in_size").items()},
        out_size_mb={k: v / 1e6 for k, v in stats("out_size").items()},
        load_s=stats("load_s"), compute_s=stats("compute_s"),
        write_s=stats("write_s"), total_s=stats("total_s"),
        read_rate_MBps=float(a.in_size.sum() / 1e6 / a.load_s.sum()),
        write_rate_MBps=float(a.out_size.sum() / 1e6 / a.write_s.sum()),
        compression_ratio=float(a.out_size.sum() / a.in_size.sum()),
        peak_rss_mb=float(a.maxrss_kb.max() / 1024),
        single_worker_obs_per_s=float(len(a) / a.total_s.sum()),
    )

    # ---- Part B: parallel scaling ----
    sweep = [int(x) for x in args.workers_sweep.split(",")]
    tasks = [(p, cfg, sha_by.get(os.path.basename(p))) for p in sample]
    scaling = []
    for w in sweep:
        t0 = time.perf_counter()
        with ProcessPoolExecutor(max_workers=w) as ex:
            list(ex.map(_bench_worker, tasks))
        wall = time.perf_counter() - t0
        scaling.append(dict(workers=w, wall_s=wall,
                            obs_per_s=len(tasks) / wall))
        print(f"[bench] workers={w:2d}  {len(tasks)/wall:6.1f} obs/s  ({wall:.1f}s)")
    best = max(scaling, key=lambda r: r["obs_per_s"])

    # ---- Part C: projections ----
    tb = pd.read_parquet(args.tier_b_manifest)
    n_full = len(tb)
    avg_out_mb = partA["out_size_mb"]["mean"]
    peak_rss_gb = partA["peak_rss_mb"] / 1024
    ram_gb = 64
    ram_limited_workers = int(ram_gb * 0.8 / max(peak_rss_gb, 0.05))
    rec_workers = min(best["workers"], ram_limited_workers, 16)
    full_runtime_s = n_full / best["obs_per_s"]

    projections = dict(
        n_full_catalog=n_full,
        raw_archive_gb=float(raw.size_bytes.sum() / 1e9),
        raw_h5_gb=float(h5.size_bytes.sum() / 1e9),
        tier_b_measured_gb=None,  # filled from du by caller/report
        avg_out_size_mb=avg_out_mb,
        projected_tier_b_gb=float(avg_out_mb * n_full / 1000),
        full_preproc_runtime_min_at_best=float(full_runtime_s / 60),
        best_workers=best["workers"],
        peak_rss_per_worker_gb=float(peak_rss_gb),
        ram_limited_workers=ram_limited_workers,
        recommended_workers=rec_workers,
        injection_storage_gb=dict(
            dev_10k=float(avg_out_mb * 10_000 / 1000),
            validation_100k=float(avg_out_mb * 100_000 / 1000),
            production_1M_materialized=float(avg_out_mb * 1_000_000 / 1000),
            note="production may be regenerated from seeds+config, not stored",
        ),
    )

    out = dict(part_a=partA, part_b_scaling=scaling, best=best,
               projections=projections,
               sample_rows=rows)
    with open(args.out, "w") as f:
        json.dump(out, f, indent=2)
    print(f"\n[bench] wrote {args.out}")
    print(f"[bench] single-worker: {partA['single_worker_obs_per_s']:.1f} obs/s | "
          f"peak RSS/worker {partA['peak_rss_mb']:.0f} MB | "
          f"compression {partA['compression_ratio']:.2f}")
    print(f"[bench] best {best['workers']}w {best['obs_per_s']:.1f} obs/s -> "
          f"full catalog {full_runtime_s/60:.1f} min; recommend {rec_workers} workers")


if __name__ == "__main__":
    main()
